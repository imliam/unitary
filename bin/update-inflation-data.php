#!/usr/bin/env php
<?php

declare(strict_types=1);

/**
 * Refreshes the bundled price index data in resources/inflation/ from the
 * official publishers:
 *
 *  - US: BLS CPI-U, all items, US city average, not seasonally adjusted (CUUR0000SA0)
 *  - UK: ONS RPI long-run series, Jan 1974 = 100 (CDKO, dataset MM23)
 *  - UK: ONS CPI index, all items, 2015 = 100 (D7BT, dataset MM23)
 *
 * Usage: php bin/update-inflation-data.php [contact-email]
 * BLS asks automated clients to identify themselves, so pass an email.
 */

use Unitary\Currency\Http\NativeHttpClient;

require dirname(__DIR__).'/vendor/autoload.php';

$contact = $argv[1] ?? 'https://github.com/imliam/unitary';
$http = new NativeHttpClient(timeout: 60);
$headers = ['User-Agent' => "unitary-php inflation data refresh ({$contact})", 'Accept' => '*/*'];
$output = dirname(__DIR__).'/resources/inflation';
$retrieved = gmdate('Y-m-d');

/**
 * @param  array<string, string>  $meta
 * @param  array<int, string>  $annual
 * @param  array<string, string>  $monthly
 */
function write_index(string $path, array $meta, array $annual, array $monthly): void
{
    ksort($annual);
    ksort($monthly);

    $data = $meta + ['annual' => $annual, 'monthly' => $monthly];
    $php = "<?php\n\n// Generated by bin/update-inflation-data.php. Do not edit by hand.\n\nreturn ".var_export($data, true).";\n";

    file_put_contents($path, $php);
    printf("%s: %d annual (%s–%s), %d monthly (latest %s)\n", basename($path), count($annual), array_key_first($annual), array_key_last($annual), count($monthly), array_key_last($monthly));
}

// BLS flat file: tab-separated series_id, year, period (M01–M12, M13 = annual average), value.
$blsUrl = 'https://download.bls.gov/pub/time.series/cu/cu.data.1.AllItems';
$annual = $monthly = [];

foreach (explode("\n", $http->get($blsUrl, $headers)) as $line) {
    $columns = array_map('trim', explode("\t", $line));

    if ($columns[0] !== 'CUUR0000SA0' || ! preg_match('/^M(\d{2})$/', $columns[2] ?? '', $period) || ! is_numeric($columns[3] ?? '')) {
        continue;
    }

    if ($period[1] === '13') {
        $annual[(int) $columns[1]] = $columns[3];
    } else {
        $monthly[$columns[1].'-'.$period[1]] = $columns[3];
    }
}

write_index($output.'/us-cpi-u.php', [
    'title' => 'CPI-U, all items in U.S. city average, all urban consumers, not seasonally adjusted (1982–84 = 100)',
    'series' => 'CUUR0000SA0',
    'currency' => 'USD',
    'publisher' => 'U.S. Bureau of Labor Statistics',
    'source' => $blsUrl,
    'retrieved' => $retrieved,
], $annual, $monthly);

// ONS time series CSV: metadata rows, then "1970","73.1", "1970 Q1",..., "1970 JAN","...".
$months = ['JAN' => '01', 'FEB' => '02', 'MAR' => '03', 'APR' => '04', 'MAY' => '05', 'JUN' => '06',
    'JUL' => '07', 'AUG' => '08', 'SEP' => '09', 'OCT' => '10', 'NOV' => '11', 'DEC' => '12'];

foreach (['cdko' => 'uk-rpi-long-run.php', 'd7bt' => 'uk-cpi.php'] as $series => $file) {
    $url = "https://www.ons.gov.uk/generator?format=csv&uri=/economy/inflationandpriceindices/timeseries/{$series}/mm23";
    $annual = $monthly = [];
    $title = '';

    foreach (explode("\n", $http->get($url, $headers)) as $line) {
        $row = str_getcsv(trim($line), escape: '');
        [$label, $value] = [$row[0] ?? '', $row[1] ?? ''];

        if ($label === 'Title') {
            $title = $value;
        } elseif (preg_match('/^(\d{4})$/', (string) $label) && is_numeric($value)) {
            $annual[(int) $label] = $value;
        } elseif (preg_match('/^(\d{4}) ([A-Z]{3})$/', (string) $label, $m) && isset($months[$m[2]]) && is_numeric($value)) {
            $monthly[$m[1].'-'.$months[$m[2]]] = $value;
        }
    }

    write_index("{$output}/{$file}", [
        'title' => $title,
        'series' => strtoupper($series),
        'currency' => 'GBP',
        'publisher' => 'Office for National Statistics',
        'source' => "https://www.ons.gov.uk/economy/inflationandpriceindices/timeseries/{$series}/mm23",
        'retrieved' => $retrieved,
    ], $annual, $monthly);
}
