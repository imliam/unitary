<?php

declare(strict_types=1);

use Unitary\Parsing\NumberWords;

it('rewrites number words into numerals', function (string $input, string $expected) {
    expect(NumberWords::normalize($input))->toBe($expected);
})->with([
    ['two and a half miles', '2 1/2 miles'],
    ['a dozen eggs', '12 eggs'],
    ['twenty-three quid', '23 quid'],
    ['one hundred and five kilometres', '105 kilometres'],
    'British "and"' => ['two thousand and one metres', '2001 metres'],
    'American, without "and"' => ['two thousand one metres', '2001 metres'],
    'a comma after a scale word' => ['one thousand, two hundred and thirty-four kg', '1234 kg'],
    'a comma after millions' => ['two million, five hundred thousand', '2500000'],
    'a comma between parts' => ['two pounds, three ounces', '2 pounds, 3 ounces'],
    ['a mile', '1 mile'],
    ['an hour', '1 hour'],
    ['half a cup', '1/2 cup'],
    ['a quarter of an hour', '1/4 hour'],
    ['three quarters of a mile', '3/4 mile'],
    ['a third of a cup', '1/3 cup'],
    ['1.2 million dollars', '1200000 dollars'],
    ['3.5k GBP', '3500 GBP'],
    ['£3.5k', '£3500'],
    ['1.2m GBP', '1200000 GBP'],
    ['$2M', '$2000000'],
    ['5k dollars', '5000 dollars'],
    ['2 billion km', '2000000000 km'],
    ['2bn km', '2000000000 km'],
    ['a couple of hours', '2 hours'],
    ['a pair of shoes', '2 shoes'],
    ['a score of years', '20 years'],
    ['a score of', '20'],
    ['a gross', '144'],
    ["a baker's dozen", '13'],
    ['a baker’s dozen rolls', '13 rolls'],
    ['half a dozen eggs', '6 eggs'],
    ['two dozen', '24'],
    ['minus forty degrees', '-40 degrees'],
    ['negative 3 °C', '-3 °C'],
    ['zero point five litres', '0.5 litres'],
    ['three point one four', '3.14'],
    ['one point two million miles', '1200000 miles'],
    ['five foot eleven', '5 foot 11'],
    ['Twenty Three Pounds', '23 Pounds'],
    ['one thousand two hundred and thirty-four metres', '1234 metres'],
    ['a hundred and five', '105'],
    ['a thousand km', '1000 km'],
    ['nineteen hundred', '1900'],
    ['ninety-nine', '99'],
    ['one and a half hours', '1 1/2 hours'],
    ['2 and a half miles', '2 1/2 miles'],
    ['two and three quarters inches', '2 3/4 inches'],
    ['an eighth of an inch', '1/8 inch'],
    ['three eighths inch', '3/8 inch'],
    ['one half', '1/2'],
    ['five million', '5000000'],
    ['£2 million', '£2000000'],
    ['1.25 thousand', '1250'],
    ['five feet and eleven inches', '5 feet and 11 inches'],
    ['a mile and a furlong', '1 mile and 1 furlong'],
    ['seven hundred thousand', '700000'],
    ['ten twenty', '10 20'],
    ['twelve point font', '12 point font'],
]);

it('leaves ordinary input untouched', function (string $input) {
    expect(NumberWords::normalize($input))->toBe($input);
})->with([
    ['5 ft 11 in'],
    ['£23 in USD'],
    ["13' 11\""],
    ['5m'],
